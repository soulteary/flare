func TaskForFavicon(src string, dest string) {
	if err := buildFavicons(src, dest); err != nil {
		log.Fatal(err)
	}
	fmt.Println("生成主题图标 ... [OK]")
}

// buildFavicons uses the original icon's alpha mask, retaining its pixel artwork.
// All image processing and content hashing happen here, never in the server.
func buildFavicons(src, dest string) error {
	raw, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if err = os.WriteFile(dest, raw, 0644); err != nil {
		return err
	}
	dir := filepath.Join(filepath.Dir(dest), "favicons")
	if err = os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if filepath.Ext(entry.Name()) == ".ico" {
			if err = os.Remove(filepath.Join(dir, entry.Name())); err != nil {
				return err
			}
		}
	}
	var manifest bytes.Buffer
	manifest.WriteString("// Code generated by build/builder. DO NOT EDIT.\npackage assets\n\nvar themeFavicons = map[string]themeFavicon{\n")
	for _, theme := range define.ThemePalettes {
		fill, err := darkestPaletteColor(theme.Colors)
		if err != nil {
			return err
		}
		icon, err := colorFavicon(raw, fill)
		if err != nil {
			return err
		}
		hash := fmt.Sprintf("%x", sha256.Sum256(icon))
		name := theme.Name + "." + hash + ".ico"
		if err = os.WriteFile(filepath.Join(dir, name), icon, 0644); err != nil {
			return err
		}
		fmt.Fprintf(&manifest, "%q: {url: %q, name: %q, etag: %q},\n", theme.Name, "/assets/favicon/"+name, "favicons/"+name, `"`+hash+`"`)
	}
	manifest.WriteString("}\n")
	source, err := format.Source(manifest.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(filepath.Dir(dest), "favicon_generated.go"), source, 0644)
}

func colorFavicon(raw []byte, background string) ([]byte, error) {
	parse := func(s string) (color.NRGBA, error) {
		var r, g, b uint8
		_, err := fmt.Sscanf(s, "#%02x%02x%02x", &r, &g, &b)
		return color.NRGBA{R: r, G: g, B: b, A: 255}, err
	}
	bg, err := parse(background)
	if err != nil {
		return nil, err
	}
	if len(raw) < 6 || binary.LittleEndian.Uint16(raw[2:4]) != 1 {
		return nil, fmt.Errorf("invalid source ICO")
	}
	count := int(binary.LittleEndian.Uint16(raw[4:6]))
	var images [][]byte
	var sizes []byte
	for i := 0; i < count; i++ {
		offset := 6 + i*16
		if offset+16 > len(raw) {
			return nil, fmt.Errorf("invalid ICO directory")
		}
		size := int(raw[offset])
		if size != 16 && size != 32 && size != 48 {
			continue
		}
		length := int(binary.LittleEndian.Uint32(raw[offset+8 : offset+12]))
		start := int(binary.LittleEndian.Uint32(raw[offset+12 : offset+16]))
		if start < 0 || length < 0 || start > len(raw) || length > len(raw)-start {
			return nil, fmt.Errorf("invalid ICO image bounds")
		}
		mask, err := png.Decode(bytes.NewReader(raw[start : start+length]))
		if err != nil {
			return nil, err
		}
		img := image.NewNRGBA(mask.Bounds())
		for y := img.Bounds().Min.Y; y < img.Bounds().Max.Y; y++ {
			for x := img.Bounds().Min.X; x < img.Bounds().Max.X; x++ {
				_, _, _, a := mask.At(x, y).RGBA()
				// Preserve the original transparency, including the squirrel cutout.
				if a == 0 {
					continue
				}
				img.SetNRGBA(x, y, color.NRGBA{R: bg.R, G: bg.G, B: bg.B, A: uint8(a >> 8)})
			}
		}
		var data bytes.Buffer
		if err = png.Encode(&data, img); err != nil {
			return nil, err
		}
		images = append(images, data.Bytes())
		sizes = append(sizes, byte(size))
	}
	if len(images) != 3 {
		return nil, fmt.Errorf("source ICO must contain 16, 32 and 48 pixel PNG images")
	}
	result := make([]byte, 6+16*len(images))
	binary.LittleEndian.PutUint16(result[2:4], 1)
	binary.LittleEndian.PutUint16(result[4:6], uint16(len(images)))
	for i, data := range images {
		entry := result[6+i*16 : 6+(i+1)*16]
		entry[0] = sizes[i]
		entry[1] = sizes[i]
		binary.LittleEndian.PutUint16(entry[4:6], 1)
		binary.LittleEndian.PutUint16(entry[6:8], 32)
		binary.LittleEndian.PutUint32(entry[8:12], uint32(len(data)))
		binary.LittleEndian.PutUint32(entry[12:16], uint32(len(result)))
		result = append(result, data...)
	}
	return result, nil
}

// darkestPaletteColor compares linear sRGB luminance rather than RGB sums.
// This selection runs only during asset generation.
func darkestPaletteColor(palette model.Palette) (string, error) {
	selected := ""
	minimum := math.Inf(1)
	linear := func(value uint8) float64 {
		c := float64(value) / 255
		if c <= 0.04045 {
			return c / 12.92
		}
		return math.Pow((c+0.055)/1.055, 2.4)
	}
	for _, candidate := range []string{palette.Background, palette.Primary, palette.Accent} {
		var r, g, b uint8
		if _, err := fmt.Sscanf(candidate, "#%02x%02x%02x", &r, &g, &b); err != nil {
			return "", err
		}
		luminance := 0.2126*linear(r) + 0.7152*linear(g) + 0.0722*linear(b)
		if luminance < minimum {
			minimum = luminance
			selected = candidate
		}
	}
	return selected, nil
}
